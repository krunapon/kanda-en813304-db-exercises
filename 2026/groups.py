def snake_groups(students, target_size):
    """เรียงตาม GPA มาก->น้อย แล้วแจกลงกลุ่มแบบงูเลื้อย"""
    students = sorted(students, key=lambda s: s[2], reverse=True)
    n = len(students)
    num_groups = math.ceil(n / target_size)
    groups = [[] for _ in range(num_groups)]
    for i, s in enumerate(students):
        rnd, pos = divmod(i, num_groups)
        g = pos if rnd % 2 == 0 else num_groups - 1 - pos
        groups[g].append(s)
    return groups


def main():
    groups = snake_groups(STUDENTS, TARGET_SIZE)

    rows = []
    for gi, members in enumerate(groups, start=1):
        avg = sum(m[2] for m in members) / len(members)
        for sid, name, gpa in sorted(members, key=lambda x: x[0]):
            rows.append([gi, sid, name, f"{gpa:.2f}", f"{avg:.2f}"])

    with open(OUTPUT_FILE, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(["กลุ่มที่", "รหัส", "ชื่อ", "gpa", "gpa เฉลี่ยของกลุ่ม"])
        w.writerows(rows)

    # ตรวจสอบความสมดุล
    avgs = [sum(m[2] for m in g) / len(g) for g in groups]
    print(f"นักศึกษา {len(STUDENTS)} คน -> {len(groups)} กลุ่ม")
    print(f"ขนาดกลุ่ม: {sorted((len(g) for g in groups), reverse=True)}")
    print(f"GPA เฉลี่ยกลุ่ม: min={min(avgs):.3f} max={max(avgs):.3f} "
          f"spread={max(avgs)-min(avgs):.3f}")


if __name__ == "__main__":
    main()
